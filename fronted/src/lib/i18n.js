/**
 * Returns a translate function t(key, vars?) for the user's selected language.
 * Falls back to English for missing keys.
 * vars: { phone: '...', level: '...', ... } replaces {placeholder} tokens.
 */
export function useTranslation() {
  const { appLanguage } = useSession();
  const lang = appLanguage || 'English';
  const dict = translations[lang] || translations.English;

  return function t(key, vars = {}) {
    let str = dict[key] ?? translations.English[key] ?? key;
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v ?? '');
    });
    return str;
  };
}
